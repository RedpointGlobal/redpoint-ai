#!/usr/bin/env bun
/**
 * bun run licenses — generate THIRD-PARTY-LICENSES.md
 *
 * Walks the installed dependency tree and emits a deterministic manifest of
 * every third-party package (name @ version → SPDX license id), grouped by
 * license. The output (THIRD-PARTY-LICENSES.md at the repo root) is committed
 * so a fresh clone ships the inventory without a network round-trip; rerun
 * this after a dependency change and commit the diff.
 *
 * Source of truth is Bun's package store (node_modules/.bun): one directory per
 * resolved package@version (`<name@version>/node_modules/<name>`, a scoped name
 * written `@scope+name@version`), so every installed version is listed — the set
 * the lockfile resolves, whatever bun hoists. node_modules/.bun/node_modules
 * holds only ONE hoisted link per package NAME (which version is bun's choice for
 * that install), so it is not the source: reading it alone dropped every other
 * installed version and let the list change with the install. We read each
 * package.json's `license` field directly rather than shelling out to an
 * npm-only tool that doesn't understand Bun's layout.
 *
 * Pass --check to verify the committed file is up to date without rewriting it
 * (exit 1 on drift); a test (scripts/__tests__/third-party-licenses-current.test.ts)
 * runs it.
 *
 * History: added for the OSS license inventory. NOTICE points here for the
 * full attribution list; this script keeps that list reproducible.
 */

import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");
const BUN_STORE = join(REPO_ROOT, "node_modules", ".bun");
const OUT = join(REPO_ROOT, "THIRD-PARTY-LICENSES.md");

export interface Pkg {
  name: string;
  version: string;
  license: string;
}

function normalizeLicense(j: any): string {
  let lic = j.license ?? j.licenses ?? "UNKNOWN";
  if (typeof lic === "object") {
    lic = Array.isArray(lic)
      ? lic.map((x: any) => x.type || x).join(" OR ")
      : lic.type || "UNKNOWN";
  }
  return String(lic);
}

function readPkg(dir: string, seen: Map<string, Pkg>): void {
  const pj = join(dir, "package.json");
  if (!existsSync(pj)) return;
  try {
    const j = JSON.parse(readFileSync(pj, "utf8"));
    if (!j.name) return;
    seen.set(`${j.name}@${j.version}`, {
      name: j.name,
      version: j.version ?? "?",
      license: normalizeLicense(j),
    });
  } catch {
    // Unparseable package.json — skip; the install itself would have failed.
  }
}

/** Every package directory in one node_modules directory (scoped ones one level deeper). */
function walk(base: string, seen: Map<string, Pkg>): void {
  let entries: string[] = [];
  try {
    entries = readdirSync(base);
  } catch {
    return;
  }
  for (const e of entries) {
    const p = join(base, e);
    if (e.startsWith("@")) {
      let subs: string[] = [];
      try {
        subs = readdirSync(p);
      } catch {
        continue;
      }
      for (const sub of subs) readPkg(join(p, sub), seen);
    } else {
      readPkg(p, seen);
    }
  }
}

/**
 * Every package@version installed in a Bun package store: each store entry's own
 * node_modules (the package itself, plus links to its dependencies — themselves
 * store entries), and the hoisted links. Deduped by name@version, sorted.
 */
export function collectPackages(bunStore: string): Pkg[] {
  const seen = new Map<string, Pkg>();
  for (const entry of readdirSync(bunStore)) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    walk(join(bunStore, entry, "node_modules"), seen);
  }
  walk(join(bunStore, "node_modules"), seen);
  return [...seen.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

/** THIRD-PARTY-LICENSES.md for a package list (deterministic: no timestamp). */
export function renderLicenses(all: Pkg[]): { content: string; licenseIds: number } {
  // Group by license id for the distribution summary.
  const byLicense = new Map<string, Pkg[]>();
  for (const p of all) {
    const arr = byLicense.get(p.license) ?? [];
    arr.push(p);
    byLicense.set(p.license, arr);
  }
  const licensesSorted = [...byLicense.entries()].sort(
    (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]),
  );

  // Build markdown. No timestamp — keep the file deterministic so the --check
  // diff only moves when the dependency set actually changes.
  const lines: string[] = [];
  lines.push("# Third-Party Licenses");
  lines.push("");
  lines.push(
    "This file is generated by `bun run licenses` (see " +
      "`scripts/generate-third-party-licenses.ts`). It lists every third-party " +
      "package in the resolved dependency tree, grouped by SPDX license " +
      "identifier. Regenerate and commit after any dependency change.",
  );
  lines.push("");
  lines.push(`Total unique packages: **${all.length}**`);
  lines.push("");
  lines.push("## License distribution");
  lines.push("");
  lines.push("| Count | License |");
  lines.push("| ----: | ------- |");
  for (const [lic, pkgs] of licensesSorted) {
    lines.push(`| ${pkgs.length} | ${lic} |`);
  }
  lines.push("");
  lines.push("## Packages by license");
  lines.push("");
  for (const [lic, pkgs] of licensesSorted) {
    lines.push(`### ${lic}`);
    lines.push("");
    for (const p of pkgs) lines.push(`- ${p.name}@${p.version}`);
    lines.push("");
  }
  return { content: lines.join("\n") + "\n", licenseIds: byLicense.size };
}

if (import.meta.main) {
  if (!existsSync(BUN_STORE)) {
    console.error(
      `error: Bun package store not found at ${BUN_STORE} — run \`bun install\` first`,
    );
    process.exit(1);
  }

  const all = collectPackages(BUN_STORE);
  const { content, licenseIds } = renderLicenses(all);

  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current === content) {
      console.log(`THIRD-PARTY-LICENSES.md is up to date (${all.length} packages)`);
      process.exit(0);
    }
    console.error(
      "THIRD-PARTY-LICENSES.md is out of date — run `bun run licenses` and commit the diff",
    );
    process.exit(1);
  }

  writeFileSync(OUT, content);
  console.log(
    `wrote THIRD-PARTY-LICENSES.md — ${all.length} packages across ${licenseIds} license ids`,
  );
}
